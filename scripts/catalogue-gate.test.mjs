import assert from 'node:assert/strict';
import {mkdtemp,mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const fixture=await mkdtemp(path.resolve('artifacts/catalogue-gate-'));
for(const dir of ['dist/assets','docs','research','scripts'])await mkdir(path.join(fixture,dir),{recursive:true});
for(const file of ['scripts/check-catalog.mjs','dist/games.json','docs/link-audit.json','docs/dos-zone-catalogue-approval.json','research/candidates.json','research/catalogue-baseline.json'])await copyFile(file,path.join(fixture,file));
const games=JSON.parse(await readFile(path.join(fixture,'dist/games.json'),'utf8'));
for(const game of games)if(game.art)await writeFile(path.join(fixture,'dist',game.art),'fixture');
const check=()=>spawnSync(process.execPath,['scripts/check-catalog.mjs'],{cwd:fixture,encoding:'utf8'});
assert.equal(check().status,0,'Exact approved pending listings pass');
const selected=games.find(g=>g.provider==='dos-zone');
selected.availability='playable';await writeFile(path.join(fixture,'dist/games.json'),JSON.stringify(games));
assert.notEqual(check().status,0,'Listing approval cannot enable a game');
selected.availability='sandbox-pending';selected.provider='unapproved-host';await writeFile(path.join(fixture,'dist/games.json'),JSON.stringify(games));
assert.notEqual(check().status,0,'Listing approval cannot authorise another provider');
selected.provider='dos-zone';await writeFile(path.join(fixture,'dist/games.json'),JSON.stringify(games));
const approval=JSON.parse(await readFile(path.join(fixture,'docs/dos-zone-catalogue-approval.json'),'utf8'));
approval.entries=approval.entries.filter(g=>g.id!==selected.id);await writeFile(path.join(fixture,'docs/dos-zone-catalogue-approval.json'),JSON.stringify(approval));
assert.notEqual(check().status,0,'A pending listing requires exact user-approved ID and URL');
console.log('Catalogue gate checks passed: exact pending batch only; approval cannot enable gameplay, authorise other providers or extend beyond listed IDs.');
